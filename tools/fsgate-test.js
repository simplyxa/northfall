#!/usr/bin/env node
'use strict';
// Тесты шлюза данных (server/fsgate.js) на настоящем PostgreSQL: правила, запись в транзакции, подписки.
// Нужны DATABASE_URL (или NODE_PATH=tools/pgshim) и таблица fs_docs. Работает с id/коллекциями-двойниками и чистит их.
process.env.STORE = 'pg'; process.env.PG_POLL_MS = '300';
const pg = require('../server/pg');
const docs = require('../server/pgdocs');
let ok = 0, bad = 0;
const T = (n, c, x) => { if (c) { ok++; console.log('  ✓ ' + n); } else { bad++; console.log('  ✗ ' + n + (x ? ' — ' + x : '')); } };
const G = require('../server/fsgate')(() => docs.firestore(), async tok => { if (!tok.startsWith('t:')) throw new Error('bad'); return tok.slice(2); });
const call = (tok, r, ip) => new Promise(res => {
  const out = { writeHead(c) { this.c = c; }, end(b) { res({ code: this.c, body: JSON.parse(b) }); } };
  G.http({ headers: { authorization: tok ? 'Bearer ' + tok : '', 'x-forwarded-for': ip || '1.1.1.1' }, socket: {} }, out, Buffer.from(JSON.stringify(r)));
});
const U = 't:tzalice', B = 't:tzbob', E = 't:tzeve', A = 't:admin';
const sleep = ms => new Promise(r => setTimeout(r, ms));
(async () => {
  const db = docs.firestore();
  const wipe = () => pg.query("DELETE FROM fs_docs WHERE path = ANY($1::text[]) OR parent LIKE 'dm/tzalice~tzbob/%' OR parent LIKE 'forum%' OR id LIKE 'gt\\_%'", [['names/gt_nick', 'players/tzalice', 'players/tzbob', 'clans/gt_clan', 'friends/tzalice~tzbob', 'saves/tzalice']]);
  await wipe();
  console.log('\nШлюз: разовые операции');
  let r = await call(null, { op: 'get', path: 'names/gt_nick' });
  T('аноним читает names', r.code === 200 && r.body.r.ex === false);
  r = await call(null, { op: 'get', path: 'players/tzalice' });
  T('аноним не читает players', r.code === 403);
  r = await call(null, { op: 'set', path: 'names/gt_nick', data: { uid: 'tzalice' } });
  T('аноним не пишет', r.code === 403);
  r = await call('bad-token', { op: 'get', path: 'names/x' });
  T('плохой токен → 401', r.code === 401);
  r = await call(U, { op: 'set', path: 'names/gt_nick', data: { uid: 'tzalice', name: 'Alice' } });
  T('tzalice занимает ник', r.code === 200, JSON.stringify(r.body));
  r = await call(B, { op: 'set', path: 'names/gt_nick', data: { uid: 'tzbob' } });
  T('tzbob не перехватывает чужой ник', r.code === 403);
  r = await call(U, { op: 'set', path: 'players/tzalice', data: { ssum: 5, seen: 1 } });
  T('tzalice пишет свою карточку', r.code === 200);
  r = await call(U, { op: 'set', path: 'players/tzalice', data: { rating: 99999 }, merge: true });
  T('рейтинг через шлюз запрещён', r.code === 403);
  r = await call(U, { op: 'update', path: 'players/tzalice', data: { lvl: 60 } });
  T('уровень через шлюз запрещён', r.code === 403);
  r = await call(U, { op: 'set', path: 'saves/tzalice', data: { gold: 1e9 } });
  T('saves клиентом не пишутся', r.code === 403);
  r = await call(U, { op: 'set', path: 'wallet/tzalice', data: { au: 1e9 } });
  T('кошелёк клиентом не пишется', r.code === 403);
  r = await call(U, { op: 'set', path: 'market/gt_m', data: { price: 1 } });
  T('рынок клиентом не пишется', r.code === 403);
  r = await call(U, { op: 'set', path: 'players/tzbob', data: { x: 1 } });
  T('чужая карточка запрещена', r.code === 403);
  r = await call(U, { op: 'create', path: 'chat/gt_c1', data: { uid: 'tzbob', text: 'hi' } });
  T('чат от чужого имени запрещён', r.code === 403);
  r = await call(U, { op: 'create', path: 'chat/gt_c1', data: { uid: 'tzalice', text: 'hi', ts: 1 } });
  T('чат от своего имени', r.code === 200);
  r = await call(U, { op: 'create', path: 'chat/gt_c1', data: { uid: 'tzalice', text: 'again' } });
  T('create существующего → code 6', r.body.code === 6);
  r = await call(U, { op: 'update', path: 'chat/gt_nope', data: { text: 'x' } });
  T('update несуществующего → code 5', r.body.code === 5 || r.code === 403);
  r = await call(U, { op: 'set', path: 'forum/gt_t', data: { title: 'T', n: { a: 1 } } });
  r = await call(U, { op: 'update', path: 'forum/gt_t', data: { 'n.a': 2, 'n.b': 3 } });
  const f = (await db.doc('forum/gt_t').get()).data();
  T('update с путём вложенного поля', f.n.a === 2 && f.n.b === 3);
  r = await call(U, { op: 'set', path: 'forum/gt_t', data: { __proto__: 1, x: { constructor: 1 } } });
  T('опасные ключи отклонены', r.code === 400 || r.code === 403);
  r = await call(U, { op: 'set', path: 'forum/gt_t', data: JSON.parse('{"__proto__":{"a":1}}') });
  T('__proto__ в JSON отклонён', r.code === 400);
  r = await call(U, { op: 'set', path: 'forum/gt_t', data: { x: 'a'.repeat(310000) } });
  T('огромный документ отклонён', r.code === 400 || r.code === 413);
  r = await call(U, { op: 'set', path: 'forum/gt_t', data: { v: { __fv: 'inc' } } });
  T('служебные значения от клиента отклонены', r.code === 400);
  r = await call(U, { op: 'get', path: 'forum/__x__' });
  T('служебные имена отклонены', r.code === 400);
  r = await call(U, { op: 'drop', path: 'forum/gt_t' });
  T('неизвестная операция', r.code === 400);
  // друзья
  console.log('\nШлюз: друзья и письма');
  const fr = { a: 'tzalice', b: 'tzbob', by: 'tzalice', st: 'p' };
  r = await call(U, { op: 'create', path: 'friends/tzalice~tzbob', data: fr });
  T('заявка в друзья', r.code === 200, JSON.stringify(r.body));
  r = await call(U, { op: 'update', path: 'friends/tzalice~tzbob', data: { st: 'ok' } });
  T('нельзя принять свою заявку', r.code === 403);
  r = await call(B, { op: 'update', path: 'friends/tzalice~tzbob', data: { st: 'ok' } });
  T('tzbob принимает', r.code === 200);
  r = await call(E, { op: 'get', path: 'friends/tzalice~tzbob' });
  T('посторонний не читает дружбу', r.code === 403);
  r = await call(B, { op: 'list', q: { p: 'friends', w: [['a', '==', 'tzalice']], l: 50 } });
  T('список друзей отдаёт документ участнику', r.code === 200 && r.body.r.docs.length === 1);
  r = await call(E, { op: 'list', q: { p: 'friends', w: [['a', '==', 'tzalice']], l: 50 } });
  T('постороннему список пуст (фильтрация)', r.code === 200 && r.body.r.docs.length === 0);
  r = await call(U, { op: 'create', path: 'dm/tzalice~tzbob/m/gt_1', data: { from: 'tzalice', text: 'item', claimed: false, item: { n: 1 } } });
  T('письмо с вещью', r.code === 200);
  r = await call(U, { op: 'update', path: 'dm/tzalice~tzbob/m/gt_1', data: { claimed: true } });
  T('отправитель не забирает свою вещь', r.code === 403);
  r = await call(B, { op: 'update', path: 'dm/tzalice~tzbob/m/gt_1', data: { claimed: true, 'item.n': 99 } });
  T('получатель не подменяет вещь', r.code === 403);
  r = await call(B, { op: 'update', path: 'dm/tzalice~tzbob/m/gt_1', data: { claimed: true } });
  T('получатель забирает один раз', r.code === 200);
  r = await call(B, { op: 'update', path: 'dm/tzalice~tzbob/m/gt_1', data: { claimed: true } });
  T('повторный забор запрещён', r.code === 403);
  r = await call(E, { op: 'list', q: { p: 'dm/tzalice~tzbob/m', l: 20 } });
  T('чужую переписку читать нельзя', r.code === 200 && r.body.r.docs.length === 0);
  const par = await Promise.all(Array.from({ length: 6 }, () => call(B, { op: 'update', path: 'dm/tzalice~tzbob/m/gt_1', data: { claimed: true } })));
  T('параллельные заборы: ни одного лишнего', par.every(x => x.code === 403));
  // нагрузка
  let lim = 0; for (let i = 0; i < 60; i++) { const x = await call(null, { op: 'get', path: 'names/zz' }, '9.9.9.9'); if (x.code === 429) lim++; }
  T('аноним ограничен по частоте', lim > 0, 'отказов ' + lim);
  // подписки
  console.log('\nШлюз: живые подписки');
  const sent = []; const send = (c, m) => sent.push(m);
  const cA = { uid: 'tzalice', open: true }, cN = { uid: '', open: true }, cE = { uid: 'tzeve', open: true };
  G.onMsg(cA, { t: 'fsl', id: 's1', q: { p: 'chat', o: [['ts', 'desc']], l: 60 } }, send);
  G.onMsg(cN, { t: 'fsl', id: 's2', q: { p: 'chat', l: 60 } }, send);
  G.onMsg(cE, { t: 'fsl', id: 's3', q: { p: 'friends', w: [['a', '==', 'tzalice']], l: 50 } }, send);
  G.onMsg(cA, { t: 'fsl', id: 's4', q: { d: 'forum/gt_t' } }, send);
  await sleep(1200);
  const s1 = sent.filter(m => m.id === 's1'), s2 = sent.find(m => m.id === 's2'), s3 = sent.filter(m => m.id === 's3'), s4 = sent.filter(m => m.id === 's4');
  T('подписка на чат: полный снимок', s1.length && s1[0].full === true && s1[0].up.some(d => d.p === 'chat/gt_c1'));
  T('аноним не подписывается на чат', s2 && s2.t === 'fse' && s2.code === 7);
  T('чужой друг-лист фильтруется', !s3.length || s3.every(m => m.up.length === 0));
  T('подписка на документ', s4.length && s4[0].up.length === 1 && s4[0].up[0].p === 'forum/gt_t');
  const n1 = s1.length;
  await call(U, { op: 'create', path: 'chat/gt_c2', data: { uid: 'tzalice', text: 'second', ts: 2 } });
  await sleep(1200);
  const s1b = sent.filter(m => m.id === 's1');
  T('новое сообщение приходит дельтой', s1b.length > n1 && s1b[s1b.length - 1].full === false && s1b[s1b.length - 1].up.some(d => d.p === 'chat/gt_c2') && s1b[s1b.length - 1].o[0] === 'chat/gt_c2');
  await call(A, { op: 'delete', path: 'chat/gt_c2' });
  await sleep(1200);
  const last = sent.filter(m => m.id === 's1').pop();
  T('удаление приходит в rm', last.rm.includes('chat/gt_c2'));
  G.onMsg(cA, { t: 'fsu', id: 's1' }, send); const cnt = sent.length;
  await call(U, { op: 'create', path: 'chat/gt_c3', data: { uid: 'tzalice', text: 'third' } }); await sleep(900);
  T('после fsu событий нет', sent.filter(m => m.id === 's1').length === sent.filter(m => m.id === 's1').length && !sent.slice(cnt).some(m => m.id === 's1'));
  G.drop(cA); G.drop(cE);
  T('stats', G.stats().enabled === true);
  await wipe(); await pg.query("DELETE FROM fs_docs WHERE id LIKE 'gt\\_%'");
  await pg.close();
  console.log('\nИтог: ' + ok + ' прошло, ' + bad + ' провалено'); process.exit(bad ? 1 : 0);
})().catch(e => { console.error('ОШИБКА ТЕСТА', e); process.exit(2); });
